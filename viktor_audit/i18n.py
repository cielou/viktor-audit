def strings(lang):
    return STRINGS.get(lang, STRINGS["en"])


def check_i18n_complete():
    """Every language must define every key the report uses."""
    base = STRINGS["en"]
    missing = {}
    for lang, table in STRINGS.items():
        for key in base:
            if key not in table:
                missing.setdefault(lang, []).append(key)
        for cid in base["check_names"]:
            if cid not in table.get("check_names", {}):
                missing.setdefault(lang, []).append("check_names." + cid)
        if len(table.get("questions", [])) != len(base["questions"]):
            missing.setdefault(lang, []).append("questions")
    return missing
